// Build the guess Set lazily (runs once on first import).
// All words from the open dictionary are lowercased; we uppercase them for comparison.
let _guessSet: Set<string> | null = null;

function getGuessSet(): Set<string> {
  if (!_guessSet) {
    _guessSet = new Set<string>();
    // Add full English dictionary (22 k+ six-letter words) in uppercase
    for (const w of ENGLISH_SIX_LETTER_WORDS) {
      _guessSet.add(w.toUpperCase());
    }
    // Ensure every target word is always valid (belt-and-suspenders)
    for (const w of WORDLE_TARGETS) {
      _guessSet.add(w.toUpperCase());
    }
  }
  return _guessSet;
}

export function getRandomTarget(exclude?: string): string {
  // Deduplicate targets array first
  const pool = [...new Set(WORDLE_TARGETS)];
  const filtered = exclude ? pool.filter(w => w !== exclude) : pool;
  const candidates = filtered.length > 0 ? filtered : pool;
  return candidates[Math.floor(Math.random() * candidates.length)];
}

export function isValidGuess(word: string): boolean {
  if (word.length !== 6) return false;
  return getGuessSet().has(word.toUpperCase());
}
